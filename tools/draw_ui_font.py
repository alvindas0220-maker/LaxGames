# Marca superior y letra base de cada acentuada; la marca va sobre una fila libre.
ACUTE = "..#.."
ACCENTED = {"á": "a", "é": "e", "í": "i", "ó": "o", "ú": "u", "Á": "A", "É": "E", "Í": "I", "Ó": "O", "Ú": "U"}


def body(char):
    return GLYPHS[char].split("/")


def cell_rows(char):
    """Devuelve las filas del glifo y su acento: (acento, filas)."""
    if char in ACCENTED:
        rows = body(ACCENTED[char])
        width = len(rows[0])
        mark = "." * (width // 2) + "#" + "." * (width - width // 2 - 1)
        if char.islower():
            rows = list(rows)
            rows[0] = "." * (width - 1) + "#"
            rows[1] = "." * (width - 2) + "#."
            return "", rows
        return mark, rows
    if char in "ñÑüÜ":
        base = "n" if char == "ñ" else "N" if char == "Ñ" else "u" if char == "ü" else "U"
        rows = list(body(base))
        mark = "#.#.#" if char in "ñÑ" else "#...#"
        if char.islower():
            rows[1] = mark if char == "ñ" else "#...#"
            if char == "ñ":
                rows[0] = ".#.#."
                rows[1] = "#.#.."
            return "", rows
        return mark, rows
    return "", body(char)


def main():
    chars = list(GLYPHS) + list(ACCENTED) + list("ñÑüÜ")
    columns = 32
    lines = (len(chars) + columns - 1) // columns
    image = [[(0, 0, 0, 0)] * (columns * CELL_W) for _ in range(lines * CELL_H)]
    entries = []
    for index, char in enumerate(chars):
        accent, rows = cell_rows(char)
        width = max(len(r) for r in rows)
        x0, y0 = (index % columns) * CELL_W, (index // columns) * CELL_H
        ink = set()
        for y, row in enumerate(rows):
            for x, bit in enumerate(row):
                if bit == "#":
                    ink.add((x, y + BODY_ROW))
        for x, bit in enumerate(accent):
            if bit == "#":
                ink.add((x, ACCENT_ROW))
        for x, y in ink:
            for dx in (-1, 0, 1):
                for dy in (-1, 0, 1):
                    image[y0 + y + dy][x0 + 1 + x + dx] = OUTLINE
        for x, y in ink:
            image[y0 + y][x0 + 1 + x] = WHITE
        entries.append(f"char id={ord(char)} x={x0} y={y0} width={width + 2} height={CELL_H} xoffset=-1 yoffset=-2 xadvance={width + 1} page=0 chnl=15")
    hero.write_png(ROOT / "assets/fonts/hud_pixel.png", image)
    header = [
        'info face="HudPixel" size=8 bold=0 italic=0 charset="" unicode=1 stretchH=100 smooth=0 aa=0 padding=0,0,0,0 spacing=1,1 outline=0',
        f"common lineHeight=11 base=7 scaleW={len(image[0])} scaleH={len(image)} pages=1 packed=0",
        'page id=0 file="hud_pixel.png"',
        f"chars count={len(entries) + 1}",
        "char id=32 x=0 y=0 width=0 height=0 xoffset=0 yoffset=0 xadvance=4 page=0 chnl=15",
    ]
    (ROOT / "assets/fonts/hud_pixel.fnt").write_text("\n".join(header + entries) + "\n", encoding="utf-8")


if __name__ == "__main__":
    main()
